/**
 * Calculate total context tokens from usage.
 * Uses the native totalTokens field when available, falls back to computing from components.
 */
export function calculateContextTokens(usage: Usage): number {
	return usage.totalTokens || usage.input + usage.output + usage.cacheRead + usage.cacheWrite;
}

/**
 * Get usage from an assistant message if available.
 * Skips aborted and error messages as they don't have valid usage data.
 */
function getAssistantUsage(msg: AgentMessage): Usage | undefined {
	if (msg.role === "assistant" && "usage" in msg) {
		const assistantMsg = msg as AssistantMessage;
		if (assistantMsg.stopReason !== "aborted" && assistantMsg.stopReason !== "error" && assistantMsg.usage) {
			return assistantMsg.usage;
		}
	}
	return undefined;
}

/**
 * Find the last non-aborted assistant message usage from session entries.
 */
export function getLastAssistantUsage(entries: SessionEntry[]): Usage | undefined {
	for (let i = entries.length - 1; i >= 0; i--) {
		const entry = entries[i];
		if (entry.type === "message") {
			const usage = getAssistantUsage(entry.message);
			if (usage) return usage;
		}
	}
	return undefined;
}

export interface ContextUsageEstimate {
	tokens: number;
	usageTokens: number;
	trailingTokens: number;
	lastUsageIndex: number | null;
}

/** Minimal tool surface for wire-size estimation (name + API schema). */
export interface WireToolSurface {
	name: string;
	description: string;
	parameters: unknown;
	/**
	 * Hand-written one-sentence summary of the tool, when it has one. Carried
	 * alongside `description` only so `compactWireToolSurface` can prefer it over
	 * a mechanically truncated first line (T01); it is folded INTO `description`
	 * on the compacted surface and never counted twice by
	 * {@link estimateToolSurfaceTokens}.
	 */
	promptSnippet?: string;
}

export interface WireEstimateInput {
	systemPromptChars: number;
	/**
	 * Full system prompt text. When provided, the system portion is
	 * density-classified (skills XML / project_context / tool guidelines are
	 * dense, not prose) instead of assumed prose at /4 — M7. Callers that only
	 * know the char count keep the legacy prose divisor.
	 */
	systemPromptText?: string;
	tools: WireToolSurface[];
	/** Active model calibration to use for structural-only estimates. */
	modelId?: string;
	/** Ignore provider usage anchors and estimate the current wire structure only. */
	structuralOnly?: boolean;
	/** Messages not yet appended to session state (e.g. pending user turn). */
	pendingMessages?: AgentMessage[];
}

export interface WireUsageEstimate extends ContextUsageEstimate {
	/** Message-only portion (same as {@link ContextUsageEstimate.tokens}). */
	messageTokens: number;
	systemTokens: number;
	toolTokens: number;
	pendingTokens: number;
}

/**
 * Estimate of a tool-surface array, memoized by ARRAY reference. Tool schemas
 * are static per session, yet this ran a JSON.stringify over every schema on
 * every presend estimate. Callers that reuse the same surfaces array (see
 * `_wireToolsForEstimate`) pay the stringify once; throwaway arrays miss and
 * are GC'd with their entry.
 */
const toolSurfaceTokensCache = new WeakMap<object, number>();

/** Estimate serialized tool-definition payload on the wire. */
export function estimateToolSurfaceTokens(tools: WireToolSurface[]): number {
	const cached = toolSurfaceTokensCache.get(tools);
	if (cached !== undefined) return cached;
	let denseChars = 0;
	for (const tool of tools) {
		denseChars += tool.name.length + tool.description.length + JSON.stringify(tool.parameters).length;
	}
	const estimate = Math.ceil(denseChars / CHARS_PER_TOKEN_DENSE);
	toolSurfaceTokensCache.set(tools, estimate);
	return estimate;
}

/**
 * One-slot memo for the system prompt token estimate. The prompt text is large
 * (tens of kB) and stable across a turn; classifying it per presend would be an
 * O(chars) rescan for the same answer. Reference/value equality on the string
 * picks the slot; any change recomputes.
 */
let systemPromptTokensMemo: { text: string; tokens: number } | undefined;

function systemPromptTokensFor(text: string): number {
	const memo = systemPromptTokensMemo;
	if (memo && memo.text === text) return memo.tokens;
	const tokens = estimateTextTokens(text);
	systemPromptTokensMemo = { text, tokens };
	return tokens;
}

/**
 * Usage anchors already fed to the calibration (M5), by assistant message
 * object. The same anchor is re-estimated every presend/TUI frame; recording
 * it once keeps the EMA from over-weighting a single (estimate, usage) pair.
 */
const calibrationRecordedAnchors = new WeakSet<AgentMessage>();

/**
 * Estimate full provider wire size: session messages + system prompt + tool
 * schemas + any pending (not-yet-appended) messages.
 *
 * M5 — this is also where the online calibration LEARNS: when the estimate
 * anchors on an assistant with real usage, the char-based estimate of the very
 * span that usage bills (messages up to and including the anchor, plus system
 * prompt and tool schemas) and `usage.totalTokens` are both known here. The
 * pair feeds an EMA per model id; the resulting factor corrects ONLY the
 * char-based portions (trailing, pending, unanchored spans) — never the real
 * usage numbers. With no recorded pairs the factor is neutral 1.0 and every
 * number below is byte-identical to the uncalibrated estimate.
 */
export function estimateWireTokens(messages: AgentMessage[], input: WireEstimateInput): WireUsageEstimate {
	let messageEstimate: ContextUsageEstimate;
	if (input.structuralOnly) {
		let tokens = 0;
		for (const message of messages) tokens += estimateTokens(message);
		tokens = Math.round(tokens * tokenEstimateFactor(input.modelId));
		messageEstimate = { tokens, usageTokens: 0, trailingTokens: tokens, lastUsageIndex: null };
	} else {
		messageEstimate = estimateContextTokens(messages);
	}
	const anchoredOnUsage = messageEstimate.lastUsageIndex !== null;
	const anchorModel = anchoredOnUsage
		? (messages[messageEstimate.lastUsageIndex as number] as AssistantMessage).model
		: undefined;
	const factor = tokenEstimateFactor(input.structuralOnly ? input.modelId : anchorModel);
	let pendingTokens = 0;
	if (input.pendingMessages) {
		for (const message of input.pendingMessages) {
			pendingTokens += estimateTokens(message);
		}
	}
	pendingTokens = Math.round(pendingTokens * factor);
	// M7: classify the system prompt's real density when the text is available —
	// skills XML, project_context, and tool guidelines are dense, not /4 prose.
	const systemTokens =
		input.systemPromptText !== undefined
			? systemPromptTokensFor(input.systemPromptText)
			: Math.ceil(input.systemPromptChars / CHARS_PER_TOKEN_PROSE);
	const toolTokens = estimateToolSurfaceTokens(input.tools);
	// M5 learning: record the (raw char estimate, real usage) pair for the span
	// the anchor's usage bills — full request: prefix + messages[0..anchor].
	// Raw (uncalibrated) estimates only, so the factor never feeds back into
	// its own training signal. Once per anchor object (WeakSet dedupe).
	if (anchoredOnUsage && anchorModel) {
		const anchorIndex = messageEstimate.lastUsageIndex as number;
		const anchor = messages[anchorIndex];
		if (!calibrationRecordedAnchors.has(anchor)) {
			calibrationRecordedAnchors.add(anchor);
			let spanEstimate = systemTokens + toolTokens;
			for (let i = 0; i <= anchorIndex; i++) {
				spanEstimate += estimateTokens(messages[i]);
			}
			recordTokenEstimateSample(anchorModel, spanEstimate, messageEstimate.usageTokens);
		}
	}
	// When the message estimate anchored on real provider usage, that usage already
	// bills the WHOLE request — system prompt and tool schemas included — so adding
	// them again would double-count ~5-30k tokens and fire the presend overflow
	// guard early. Only the estimate-only path (no usage yet, e.g. first turn)
	// still needs the explicit prefix sum (calibrated: it is char-based). The
	// fields stay populated either way so callers can inspect the prefix surface.
	const tokens =
		messageEstimate.tokens + pendingTokens + (anchoredOnUsage ? 0 : Math.round((systemTokens + toolTokens) * factor));
	return {
		...messageEstimate,
		messageTokens: messageEstimate.tokens,
		systemTokens,
		toolTokens,
		pendingTokens,
		tokens,
	};
}

function getLastAssistantUsageInfo(messages: AgentMessage[]): { usage: Usage; index: number } | undefined {
	for (let i = messages.length - 1; i >= 0; i--) {
		const usage = getAssistantUsage(messages[i]);
		if (usage) return { usage, index: i };
	}
	return undefined;
}

/**
 * Estimate context tokens from messages, using the last assistant usage when available.
 * If there are messages after the last usage, estimate their tokens with estimateTokens.
 *
 * M5 — char-based portions (the trailing span after the anchor, or the whole
 * span when no usage anchors it) are multiplied by the per-model calibration
 * factor learned from real usage (see estimateWireTokens). The anchored usage
 * itself is NEVER scaled. Neutral 1.0 factor (no recorded pairs) reproduces
 * the uncalibrated numbers exactly.
 */
export function estimateContextTokens(messages: AgentMessage[]): ContextUsageEstimate {
	const usageInfo = getLastAssistantUsageInfo(messages);

	if (!usageInfo) {
		let estimated = 0;
		for (const message of messages) {
			estimated += estimateTokens(message);
		}
		estimated = Math.round(estimated * tokenEstimateFactor());
		return {
			tokens: estimated,
			usageTokens: 0,
			trailingTokens: estimated,
			lastUsageIndex: null,
		};
	}

	const usageTokens = calculateContextTokens(usageInfo.usage);
	let trailingTokens = 0;
	for (let i = usageInfo.index + 1; i < messages.length; i++) {
		trailingTokens += estimateTokens(messages[i]);
	}
	trailingTokens = Math.round(
		trailingTokens * tokenEstimateFactor((messages[usageInfo.index] as AssistantMessage).model),
	);

	return {
		tokens: usageTokens + trailingTokens,
		usageTokens,
		trailingTokens,
		lastUsageIndex: usageInfo.index,
	};
}

/**
 * Compute a dynamic reserve that scales with context window size.
 * - Small windows (≤200k): 10% of window, or the configured reserve.
 * - Large windows (>200k): the configured reserve, a 20k floor, AND a 2.5%
 *   floor. The percentage floor matters for very large windows: a flat 20k on a
 *   1M window is only 2% (trigger at ~98%, dangerously close to the hard limit
 *   if the token estimate runs low); 2.5% keeps ~25k headroom (~97.5%), leaving
 *   slack for estimation error before the model rejects on overflow.
 */
export function computeDynamicReserve(contextWindow: number, configuredReserve: number): number {
	if (!Number.isFinite(contextWindow) || contextWindow <= 0) return 0;
	const rawReserve =
		contextWindow > 200_000
			? Math.max(configuredReserve, 20_000, Math.ceil(contextWindow * 0.025))
			: Math.max(configuredReserve, Math.floor(contextWindow * 0.1));
	const maxUsableReserve = Math.max(1, Math.floor(contextWindow * 0.5));
	return Math.min(rawReserve, maxUsableReserve);
}

/**
 * Tokens to reserve for the *next* assistant thinking block before send.
 * Mirrors `@pit/ai` `adjustMaxTokensForThinking` defaults so presend compaction
 * fires before a reasoning-heavy turn overflows. Does NOT inflate
 * `estimateWireTokens` (UI % stays message/wire-only).
 *
 * Returns 0 when thinking is off or the model has no reasoning capability.
 */
export function resolveThinkingHeadroom(
	model: { reasoning?: boolean } | undefined,
	thinkingLevel: ThinkingLevel | "off" | undefined,
	customBudgets?: { minimal?: number; low?: number; medium?: number; high?: number },
): number {
	if (!model?.reasoning) return 0;
	if (!thinkingLevel || thinkingLevel === "off") return 0;
	const defaults = { minimal: 1024, low: 2048, medium: 8192, high: 16384 };
	const budgets = { ...defaults, ...customBudgets };
	// Effort-only levels (xhigh/max/ultra) have no token budget of their own;
	// reserve the high budget so presend compaction still leaves headroom.
	if (thinkingLevel === "xhigh" || thinkingLevel === "max" || thinkingLevel === "ultra") {
		return budgets.high;
	}
	return budgets[thinkingLevel] ?? budgets.medium;
}

/**
 * Effective verbatim-retention budget for findCutPoint.
 *
 * The configured `keepRecentTokens` (default 20k) is a flat floor. On a large
 * window the trigger scales (computeDynamicReserve) but a flat 20k retention
 * would discard ~950k of raw recent messages in favor of a lossy summary. Scale
 * retention to 10% of the window above 200k (same threshold/percentage as the
 * reserve), keeping the configured value as a floor. Windows ≤200k are byte-
 * identical (10% of 200k == the 20k default floor).
 */
export function effectiveKeepRecentTokens(configured: number, contextWindow?: number): number {
	if (!contextWindow || contextWindow <= 200_000) {
		return configured;
	}
	return Math.max(configured, Math.floor(contextWindow * 0.1));
}

/**
 * Fraction of the LIVE context a manual `/compact` keeps verbatim.
 *
 * {@link effectiveKeepRecentTokens} scales the keep-recent budget with the
 * WINDOW (10% of it above 200k), which is right for auto-compaction: that fires
 * near the hard threshold, so on a 1M window it keeps ~100k out of ~900k — a 90%
 * fold. But the floor is FLAT, so the same 100k against a session that is merely
 * 111k reclaims 8%, and against 194k reclaims 48% (measured). A manual compaction
 * is an explicit "reclaim now" issued at whatever pressure the user happens to be
 * at, so its budget has to scale with CURRENT USAGE instead — 25% keeps the fold
 * at ~75% across every session size. Never exceeds the window-scaled value (a
 * manual compaction is never gentler than the automatic one) and never drops
 * below {@link ADAPTIVE_KEEP_MIN_FLOOR}.
 */
export const MANUAL_COMPACT_KEEP_FRACTION = 0.25;

/**
 * Keep-recent budget for a MANUAL compaction. See
 * {@link MANUAL_COMPACT_KEEP_FRACTION}. Falls back to the window-scaled value
 * when the live size is unknown or non-positive, so a caller that cannot measure
 * gets exactly today's behaviour.
 */
export function manualKeepRecentTokens(configured: number, contextWindow?: number, liveTokens?: number): number {
	const windowScaled = effectiveKeepRecentTokens(configured, contextWindow);
	if (!liveTokens || liveTokens <= 0) return windowScaled;
	const usageScaled = Math.floor(liveTokens * MANUAL_COMPACT_KEEP_FRACTION);
	return Math.min(windowScaled, Math.max(ADAPTIVE_KEEP_MIN_FLOOR, usageScaled));
}

/** Legacy flat floor for the assumed summary + structural frame a compaction inserts. */
const COMPACTION_SUMMARY_TOKEN_BUDGET_FLOOR = 8_000;
/** Never retain less verbatim recent context than this, whatever the pressure. */
const ADAPTIVE_KEEP_MIN_FLOOR = 8_000;

/**
 * Tokens to budget for the summary + structural frame a compaction inserts (M8).
 *
 * The flat 8k systematically UNDER-estimated the real insertion: generateSummary
 * caps output at 0.8×reserveTokens (see summarizationMaxTokens), and observed
 * summaries reach ~13k once the structural frame + file digests ride along — so
 * the post-compaction context landed back above the re-check threshold on small
 * windows and the "rare" second LLM pass became structural. Derive the budget
 * from the summarizer's REAL ceiling (0.8×reserve, floored at the legacy 8k so
 * tiny configured reserves keep the old behaviour) and add the estimated
 * structural frame when the caller knows it (the frame merges forward across
 * compactions, so the previous compaction's persisted details predict it).
 */
export function compactionSummaryTokenBudget(settings: CompactionSettings, frameTokensEstimate?: number): number {
	const summaryCeiling = Math.max(COMPACTION_SUMMARY_TOKEN_BUDGET_FLOOR, Math.ceil(settings.reserveTokens * 0.8));
	const frame = Number.isFinite(frameTokensEstimate) ? Math.max(0, Math.floor(frameTokensEstimate as number)) : 0;
	return summaryCeiling + frame;
}

/**
 * Estimate the tokens of the structural frame (operation lists + file digests)
 * the NEXT compaction will append, from a previous compaction entry's persisted
 * `details`. The lists merge forward across compactions, so the previous frame
 * is the best available predictor. Returns undefined when there is no usable
 * signal (no previous compaction, empty/legacy details).
 */
export function estimateCompactionFrameTokens(details: unknown): number | undefined {
	if (typeof details !== "object" || details === null) return undefined;
	const d = details as CompactionDetails;
	let chars = 0;
	const addList = (arr: unknown): void => {
		if (!Array.isArray(arr)) return;
		for (const item of arr) {
			if (typeof item === "string") chars += item.length + 1;
		}
	};
	addList(d.readFiles);
	addList(d.modifiedFiles);
	addList(d.searches);
	addList(d.shellCmds);
	addList(d.mcpCalls);
	if (typeof d.fileDigests === "object" && d.fileDigests !== null) {
		for (const [path, digest] of Object.entries(d.fileDigests)) {
			if (typeof digest === "string") chars += path.length + digest.length + 8;
		}
	}
	if (chars === 0) return undefined;
	// The frame is XML tags + paths/commands — dense by construction.
	return Math.ceil(chars / CHARS_PER_TOKEN_DENSE);
}

/**
 * Adaptive verbatim-retention budget for a SINGLE compaction pass.
 *
 * The post-compaction context is ≈ kept-recent + summary. When that lands back
 * above the re-check threshold (the soft threshold, or the hard one on windows
 * too small for a positive soft band), runAutoCompaction used to run a SECOND
 * full pipeline — 1-2 extra LLM calls. On small windows the default keep alone
 * exceeds the target, so the second pass was structural, not incidental. This
 * shrinks the keep so one pass suffices: keep ≤ target − summary budget (M8:
 * derived from the real summarizer ceiling + previous frame estimate, no longer
 * a flat 8k), floored at max(8k, keepRecentTokens/2) so quality never collapses
 * (the second pass remains as fallback when the floor wins). Returns undefined
 * when no shrink is needed — normal windows are byte-identical to the legacy
 * path.
 */
export function adaptiveKeepRecentTokens(
	contextWindow: number,
	settings: CompactionSettings,
	frameTokensEstimate?: number,
): number | undefined {
	if (!Number.isFinite(contextWindow) || contextWindow <= 0) return undefined;
	const reserve = computeDynamicReserve(contextWindow, settings.reserveTokens);
	const effectiveKeep = effectiveKeepRecentTokens(settings.keepRecentTokens, contextWindow);
	const hardThreshold = contextWindow - reserve;
	const softThreshold = hardThreshold - effectiveKeep;
	// Mirror the post-compaction re-check: shouldCompactSoft only fires with a
	// positive soft threshold; otherwise the hard threshold is the bar.
	const target = softThreshold > 0 ? softThreshold : hardThreshold;
	const keepMax = target - compactionSummaryTokenBudget(settings, frameTokensEstimate);
	if (keepMax >= effectiveKeep) return undefined;
	const floor = Math.max(ADAPTIVE_KEEP_MIN_FLOOR, Math.floor(settings.keepRecentTokens / 2));
	const adapted = Math.min(effectiveKeep, Math.max(floor, keepMax));
	return adapted < effectiveKeep ? adapted : undefined;
}

/** Absolute minimum floor for the proactive prune; below this the cache cost is not worth it. */
const PROACTIVE_PRUNE_MIN_FLOOR = 64_000;

/**
 * Context size (tokens) below which the proactive stale-tool-output prune is NOT
 * worth running. The prune rewrites old messages, which busts the provider
 * prompt cache — only pay that when there is real pressure.
 *
 * A flat floor over-prunes on very large windows: at 64k a 1M-window session is
 * ~6% full, so pruning there churns the cache while ~94% of room remains. Scale
 * the floor to 25% of the window, keeping 64k as an absolute minimum (windows up
 * to 256k stay at 64k, byte-identical to the old behaviour). A positive explicit
 * `override` (PIT_PROACTIVE_PRUNE_FLOOR) always wins.
 */
export function proactivePruneFloor(contextWindow: number, override?: number): number {
	if (override !== undefined && Number.isFinite(override) && override > 0) return override;
	const scaled = Number.isFinite(contextWindow) && contextWindow > 0 ? Math.floor(contextWindow * 0.25) : 0;
	return Math.max(PROACTIVE_PRUNE_MIN_FLOOR, scaled);
}

/** Hysteresis threshold: only re-compact if deficit grew by this many tokens since last compaction. */
const COALESCING_THRESHOLD_TOKENS = 8192;

/**
 * Check if compaction should trigger based on context usage.
 * Uses adaptive reserve scaling and hysteresis to avoid compaction churn.
 *
 * @param lastCompactionDeficit - deficit at last compaction trigger (0 if none). Callers
 *   should persist this value and pass it back on subsequent checks.
 */
export function shouldCompact(
	contextTokens: number,
	contextWindow: number,
	settings: CompactionSettings,
	lastCompactionDeficit = 0,
): boolean {
	if (!settings.enabled) return false;
	if (!Number.isFinite(contextWindow) || contextWindow <= 0) return false;
	const reserve = computeDynamicReserve(contextWindow, settings.reserveTokens);
	const threshold = contextWindow - reserve;
	if (contextTokens <= threshold) return false;
	const deficit = contextTokens - threshold;
	if (lastCompactionDeficit === 0) return true;
	return deficit > lastCompactionDeficit + COALESCING_THRESHOLD_TOKENS;
}

/**
 * Soft (predictive) trigger: fire compaction ~one `keepRecentTokens` window
 * BEFORE the hard threshold. Run in the background while the user reads the
 * just-finished turn, so the summary is ready before they send the next prompt
 * (no visible compaction wait). The hard `shouldCompact` stays as the
 * synchronous fallback for turns that jump straight past it.
 *
 * Returns false once at/over the hard threshold — there the caller must compact
 * synchronously, not defer.
 */
export function shouldCompactSoft(contextTokens: number, contextWindow: number, settings: CompactionSettings): boolean {
	if (!settings.enabled) return false;
	if (!Number.isFinite(contextWindow) || contextWindow <= 0) return false;
	const reserve = computeDynamicReserve(contextWindow, settings.reserveTokens);
	const hardThreshold = contextWindow - reserve;
	if (contextTokens > hardThreshold) return false; // hard path owns this
	// Scale the predictive band with the window (same 10%-above-200k rule as retention) so a
	// large window gets a real head-start instead of a flat 20k sliver below the hard threshold
	// that a single big turn would jump straight past into the synchronous path. Windows ≤200k
	// are byte-identical (effectiveKeepRecentTokens returns the raw keepRecentTokens).
	const softThreshold = hardThreshold - effectiveKeepRecentTokens(settings.keepRecentTokens, contextWindow);
	return softThreshold > 0 && contextTokens > softThreshold;
}

