/** Details stored in CompactionEntry.details for structured summary frame.
 *
 * Older sessions only carry `readFiles` and `modifiedFiles`. The remaining
 * fields are populated by the structured summary frame and are loaded
 * defensively when present. Extends the shared {@link SummaryDetails} (the same
 * operation lists branch summarization persists) with compaction-only digests.
 */
export interface CompactionDetails extends SummaryDetails {
	/** path -> top symbols, derived at compaction time. Lossy guide; re-read for current content. */
	fileDigests?: Record<string, string>;
}

/**
 * Extract file operations from messages and previous compaction entries.
 */
function extractFileOperations(
	messages: AgentMessage[],
	entries: SessionEntry[],
	prevCompactionIndex: number,
): FileOperations {
	const fileOps = createFileOps();

	// Collect from previous compaction's details (if pi-generated)
	if (prevCompactionIndex >= 0) {
		const prevCompaction = entries[prevCompactionIndex] as CompactionEntry;
		if (!prevCompaction.fromHook && prevCompaction.details) {
			// fromHook field kept for session file compatibility
			mergeSummaryDetailsIntoFileOps(prevCompaction.details as CompactionDetails, fileOps);
		}
	}

	// Extract from tool calls in messages
	for (const msg of messages) {
		extractFileOpsFromMessage(msg, fileOps);
	}

	return fileOps;
}

